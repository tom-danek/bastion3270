const STRINGS = Object.freeze({ en: EN, cs: CS });

/**
 * The language to use: a stored choice if it is supported, else the first supported browser
 * language (`cs-CZ` → `cs`), else English.
 *
 * @param {string|null} stored  the user's choice (`localStorage`), or null
 * @param {readonly string[]} browser  `navigator.languages`
 */
export function pickLanguage(stored, browser) {
  if (stored && Object.hasOwn(STRINGS, stored)) return stored;
  for (const tag of browser || []) {
    const base = String(tag).toLowerCase().split("-")[0];
    if (Object.hasOwn(STRINGS, base)) return base;
  }
  return "en";
}

/**
 * The text for `key` in `lang` with `{name}` placeholders filled from `params`.
 *
 * @param {string} lang
 * @param {string} key
 * @param {Record<string, string|number>} [params]
 */
export function t(lang, key, params = {}) {
  const table = STRINGS[lang] || EN;
  const text = Object.hasOwn(table, key) ? table[key] : Object.hasOwn(EN, key) ? EN[key] : key;
  return text.replace(/\{(\w+)\}/g, (all, name) => (Object.hasOwn(params, name) ? String(params[name]) : all));
}

/** `true` if both languages have exactly the same keys (checked by the tests). */
export function complete() {
  const en = Object.keys(EN).sort().join();
  return Object.keys(CS).sort().join() === en;
}
