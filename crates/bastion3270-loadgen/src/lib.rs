//! Load and soak generator for the `bastion3270` gateway.
//!
//! One process plays both ends of the gateway:
//! * [`host`] — simulated TN3270E hosts that answer every AID with a new full screen after a
//!   configurable delay (an ISPF-like panel, so frames have realistic size);
//! * [`browser`] — simulated browsers: WebSocket clients that open a session, type, press Enter
//!   and measure the time until the answering screen arrives.
//!
//! [`run`] ramps up the sessions, keeps them busy, and returns a [`Report`]; [`proc`] samples the
//! gateway process (memory, CPU, file descriptors) so memory per session can be derived.
//! [`tls`] puts TLS on both sides (host connection and the gateway's own listener).

pub mod browser;
pub mod host;
pub mod proc;
pub mod stats;
pub mod tls;

use std::net::SocketAddr;
use std::path::Path;
use std::sync::Arc;
use std::time::{Duration, Instant};

pub use stats::Report;

/// What to run.
#[derive(Debug, Clone)]
pub struct LoadConfig {
    /// Gateway HTTP address.
    pub gateway: SocketAddr,
    /// Profile id the browsers open (the gateway profile points at the simulated host).
    pub profile: String,
    /// Concurrent sessions.
    pub sessions: usize,
    /// Time over which the sessions are opened.
    pub ramp: Duration,
    /// How long all sessions keep working after the ramp.
    pub duration: Duration,
    /// Pause between two operator actions of one session (type + Enter).
    pub think: Duration,
    /// Open a new session when the gateway ends one (an operator logs on again), so a run can
    /// last longer than the gateway's session lifetime.
    pub reopen: bool,
    /// Connect to the gateway over WSS with this client configuration ([`tls::client_config`]).
    pub tls: Option<Arc<rustls::ClientConfig>>,
}

/// Runs the load and returns the measurements. `on_sample` is called about every
/// `sample_every` with the report so far (progress output, soak trend).
pub async fn run(
    cfg: LoadConfig,
    sample_every: Duration,
    mut on_sample: impl FnMut(&Report),
) -> Report {
    let stats = Arc::new(stats::Stats::default());
    let started = Instant::now();
    let stop_at = started + cfg.ramp + cfg.duration;
    let mut tasks = Vec::with_capacity(cfg.sessions);
    let step = cfg
        .ramp
        .checked_div(u32::try_from(cfg.sessions.max(1)).unwrap_or(u32::MAX))
        .unwrap_or_default();
    for i in 0..cfg.sessions {
        let user = browser::Browser {
            gateway: cfg.gateway,
            profile: cfg.profile.clone(),
            think: cfg.think,
            reopen: cfg.reopen,
            stop_at,
            stats: Arc::clone(&stats),
            // Spread the actions of the sessions over the think time.
            phase: cfg
                .think
                .mul_f64(f64::from(u32::try_from(i % 1000).unwrap_or(0)) / 1000.0),
            tls: cfg.tls.clone(),
        };
        tasks.push(tokio::spawn(user.run()));
        tokio::time::sleep(step).await;
    }
    let mut ticker = tokio::time::interval(sample_every);
    ticker.tick().await;
    while Instant::now() < stop_at {
        tokio::select! {
            _ = ticker.tick() => on_sample(&stats.report(started.elapsed())),
            () = tokio::time::sleep_until(stop_at.into()) => {}
        }
    }
    for t in tasks {
        let _ = t.await;
    }
    stats.report(started.elapsed())
}

/// TLS settings of a generated gateway configuration (PEM files, e.g. from
/// [`tls::write_test_pki`]).
#[derive(Debug, Clone, Copy, Default)]
pub struct GatewayTls<'a> {
    /// CA the gateway trusts for the simulated hosts: the host connection uses TLS.
    pub host_ca: Option<&'a Path>,
    /// Certificate and key of the gateway's own listener: browsers connect over WSS.
    pub listener: Option<(&'a Path, &'a Path)>,
}

/// A gateway configuration for a load test: lab mode (no authentication), limits above the
/// planned load, one profile `load` pointing at the simulated hosts.
#[must_use]
pub fn gateway_config(
    host: SocketAddr,
    sessions: usize,
    bind: SocketAddr,
    metrics: SocketAddr,
    tls: GatewayTls<'_>,
) -> String {
    let max = sessions.saturating_mul(2).max(16);
    // TOML basic strings: a Windows path's backslashes must be escaped.
    let quoted = |p: &Path| format!("{:?}", p.display().to_string());
    let listener = tls.listener.map_or_else(String::new, |(cert, key)| {
        format!(
            "\n[server.tls]\ncert = {}\nkey = {}\n",
            quoted(cert),
            quoted(key)
        )
    });
    let host_tls = tls.host_ca.map_or_else(
        || "tls_mode = \"disabled\"".to_owned(),
        |ca| format!("tls_mode = \"enabled\"\nca_cert = {}", quoted(ca)),
    );
    format!(
        r#"# Generated by bastion3270-loadgen: lab configuration for load tests only.
[server]
bind = "{bind}"
metrics_bind = "{metrics}"
{listener}
[limits]
max_sessions = {max}
max_connections = {max}
max_pending_handshakes = {max}
max_messages_per_second = 1000

[[profiles]]
id = "load"
name = "Load test host"
[profiles.connection]
{host_tls}
host = "{}"
port = {}
terminal_model = "Model2"
idle_timeout_ms = 600000
"#,
        host.ip(),
        host.port()
    )
}
