#!/usr/bin/env python3
"""Generates the EBCDIC code page tables of bastion3270-core from the x3270 reference.

    python3 -I tools/gen-codepages.py vendor/x3270-ref/Common/unicode.c \
        > crates/bastion3270-core/src/ebcdic/tables.rs && cargo fmt

Reads the single-byte tables (`uni[]`: EBCDIC X'41'..X'FE' -> UCS-2, host code page, CGCSGID)
and the aliases (`cpaliases[]`) of x3270's Common/unicode.c. The x3270 sources are not part of
this repository (see docs/DEVELOPMENT.md); the generated file is committed.
"""
import re
import sys

UT_SIZE = 190
DEFAULT_CGEN = 0x02B90000  # x3270 codepage.c: a 16-bit CGCSGID gets character set 697


def strip_comments(text):
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def array_body(source, start):
    begin = source.index(start)
    return source[begin:source.index("\n};", begin)]


def parse(path):
    source = open(path, encoding="utf-8").read()
    tables = []
    body = strip_comments(array_body(source, "static uni_t uni[] = {"))
    pattern = re.compile(
        r'\{\s*"([^"]+)"\s*,\s*\{([^}]*)\}\s*,\s*"([^"]*)"\s*,\s*"([^"]*)"\s*,'
        r'\s*(true|false)\s*,\s*"([^"]*)"\s*\}'
    )
    for name, codes, host, cgcsgid, is_dbcs, _kybd in pattern.findall(body):
        values = [int(v, 0) for v in codes.replace("\n", " ").split(",") if v.strip()]
        if len(values) != UT_SIZE:
            sys.exit(f"{name}: {len(values)} entries, expected {UT_SIZE}")
        if is_dbcs == "true":
            continue
        cg = int(cgcsgid, 0)
        if cg & ~0xFFFF == 0:
            cg |= DEFAULT_CGEN
        tables.append((name, host, cg, values))
    aliases = re.findall(
        r'\{\s*"([^"]+)"\s*,\s*"([^"]+)"\s*\}',
        strip_comments(array_body(source, "cpalias_t cpaliases[] = {")),
    )
    return tables, aliases


def variant(name):
    return name[0].upper() + name[1:]


def main():
    tables, aliases = parse(sys.argv[1])
    names = {t[0] for t in tables}
    alias_of = {}
    for alias, canon in aliases:
        if canon in names:
            alias_of.setdefault(canon, []).append(alias)
    out = []
    w = out.append
    w("//! EBCDIC code page tables, generated by `tools/gen-codepages.py` from the x3270")
    w("//! reference (`Common/unicode.c`, tables `uni[]` and `cpaliases[]`). Do not edit by hand.")
    w("//!")
    w("//! Each table maps EBCDIC `X'41'..=X'FE'` to UCS-2 (`0` = no character); the other codes")
    w("//! are mapped programmatically by [`StaticCodePage`].")
    w("")
    w("use super::StaticCodePage;")
    w("")
    for name, host, cg, values in tables:
        w(f"/// IBM code page {host} (`{name}`), CGCSGID `0x{cg:08X}`.")
        w(f"pub static {name.upper()}: StaticCodePage = StaticCodePage::from_ut_table(")
        w(f'    "{name}",')
        w(f'    "{host}",')
        w(f"    0x{cg >> 16:04X}_{cg & 0xFFFF:04X},")
        w("    [")
        for i in range(0, UT_SIZE, 8):
            w("        " + ", ".join(f"0x{v:04X}" for v in values[i:i + 8]) + ",")
        w("    ],")
        w(");")
        w("")
    w("/// The built-in single-byte host code pages.")
    w("#[derive(Debug, Default, Clone, Copy, PartialEq, Eq, Hash)]")
    w("pub enum CodePageId {")
    for name, host, _cg, _v in tables:
        w(f"    /// `{name}` (host code page {host}).")
        if name == "cp037":
            w("    #[default]")
        w(f"    {variant(name)},")
    w("}")
    w("")
    w("impl CodePageId {")
    w("    /// Every built-in code page, in the order of the x3270 table.")
    w("    pub const ALL: &'static [Self] = &[")
    for name, *_ in tables:
        w(f"        Self::{variant(name)},")
    w("    ];")
    w("")
    w("    /// The table of this code page.")
    w("    #[must_use]")
    w("    pub const fn codepage(self) -> &'static StaticCodePage {")
    w("        match self {")
    for name, *_ in tables:
        w(f"            Self::{variant(name)} => &{name.upper()},")
    w("        }")
    w("    }")
    w("")
    w("    /// Canonical name (`cp037`, ...).")
    w("    #[must_use]")
    w("    pub const fn name(self) -> &'static str {")
    w("        self.codepage().name")
    w("    }")
    w("")
    w("    /// The x3270 aliases of this code page (`german`, `german-euro`, ...).")
    w("    #[must_use]")
    w("    pub const fn aliases(self) -> &'static [&'static str] {")
    w("        match self {")
    for name, *_ in tables:
        listed = ", ".join(f'"{a}"' for a in alias_of.get(name, []))
        w(f"            Self::{variant(name)} => &[{listed}],")
    w("        }")
    w("    }")
    w("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
